"""浏览器自动登录与 Cookie 持久化。

优先用本机 chromedriver / geckodriver 打开百度登录页，用户扫码或输密码后
自动抓取 cookie；检测不到驱动时退而读取 Firefox 的 cookie 数据库。
保存格式是 Netscape cookies.txt，curl / wget 也能直接复用。
"""

from __future__ import annotations

import json
import os
import shutil
import sqlite3
import subprocess
import tempfile
import threading
import time
import urllib.error
import urllib.request
from pathlib import Path
from typing import Callable, Dict, Optional, Tuple

from . import config

LOGIN_URL = "https://passport.baidu.com/v2/?login&u=https://pan.baidu.com/disk/home"
LOGIN_KEYS = ("BDUSS", "BDUSS_BFESS", "STOKEN")

LOGIN_STATE: Dict[str, object] = {
    "state": "idle",       # idle | starting | waiting | success | error
    "message": "",
    "method": "",
    "updated": 0.0,
}
_LOGIN_LOCK = threading.Lock()


def _set_login_state(state: str, message: str, method: str = "") -> None:
    with _LOGIN_LOCK:
        LOGIN_STATE.update(state=state, message=message, method=method, updated=time.time())


def login_status() -> Dict[str, object]:
    with _LOGIN_LOCK:
        return dict(LOGIN_STATE)


# ---------- cookies.txt ----------

def load_cookies() -> Dict[str, str]:
    path = config.cookies_file()
    cookies: Dict[str, str] = {}
    try:
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line or line.startswith("#") and not line.startswith("#HttpOnly_"):
                continue
            fields = (line[len("#HttpOnly_"):] if line.startswith("#HttpOnly_") else line).split("\t")
            if len(fields) >= 7:
                name, value = fields[5], fields[6]
                if name and name != "undefined":
                    cookies[name] = value
    except OSError:
        pass
    return cookies


def save_cookies(cookies: Dict[str, str]) -> None:
    config.ensure_dirs()
    path = config.cookies_file()
    lines = ["# Netscape HTTP Cookie File", "# Generated by YunX-Linux", ""]
    for name, value in sorted(cookies.items()):
        if not name or name == "undefined" or value is None:
            continue
        lines.append("\t".join([".baidu.com", "TRUE", "/", "TRUE", "0", name, str(value)]))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    try:
        path.chmod(0o600)
    except OSError:
        pass


def has_login(cookies: Optional[Dict[str, str]] = None) -> bool:
    cookies = cookies if cookies is not None else load_cookies()
    return any(key in cookies for key in LOGIN_KEYS)


# ---------- Firefox 数据库兜底 ----------

def from_firefox() -> Dict[str, str]:
    """Firefox 的 cookie 数据库未加密，可直接读；读取前先复制，避免锁库。"""
    base = Path.home() / ".mozilla" / "firefox"
    if not base.exists():
        return {}
    cookies: Dict[str, str] = {}
    for profile in base.glob("*.default*"):
        source = profile / "cookies.sqlite"
        if not source.exists():
            continue
        try:
            with tempfile.NamedTemporaryFile(suffix=".sqlite", delete=False) as tmp:
                temp_path = tmp.name
            shutil.copyfile(source, temp_path)
            connection = sqlite3.connect(temp_path)
            try:
                rows = connection.execute(
                    "SELECT host, name, value FROM moz_cookies WHERE host LIKE '%baidu.com%'"
                ).fetchall()
            finally:
                connection.close()
            for host, name, value in rows:
                if name and name != "undefined" and value:
                    cookies[name] = value
        except (OSError, sqlite3.Error):
            pass
        finally:
            try:
                os.unlink(temp_path)
            except OSError:
                pass
    return cookies


# ---------- WebDriver 最小客户端 ----------

class WebDriverError(Exception):
    pass


def _wd_request(base: str, method: str, path: str, payload=None, timeout: int = 15):
    data = json.dumps(payload).encode("utf-8") if payload is not None else None
    request = urllib.request.Request(
        base + path, data=data, method=method,
        headers={"Content-Type": "application/json"},
    )
    with urllib.request.urlopen(request, timeout=timeout) as response:
        return json.loads(response.read().decode("utf-8"))


def _find_driver() -> Optional[Tuple[str, str]]:
    for name in ("chromedriver", "geckodriver", "chromium-driver"):
        found = shutil.which(name)
        if found:
            return name, found
    return None


def login_via_browser(driver_name: Optional[str] = None, timeout: int = 300,
                      headless: bool = False,
                      on_status: Optional[Callable[[str], None]] = None) -> Dict[str, str]:
    """启动浏览器驱动，等待用户登录，自动抓取百度 cookie。"""
    found = _find_driver()
    if not found and driver_name:
        raise WebDriverError(
            f"找不到 {driver_name}。请安装浏览器驱动：\n"
            "  Debian/Ubuntu: sudo apt install chromium-driver\n"
            "  Fedora:        sudo dnf install chromedriver\n"
            "  Firefox:       sudo apt install firefox-esr firefox-geckodriver\n"
            "也可以直接导入 Firefox 已登录的 Cookie：yunx login --firefox"
        )
    if not found:
        raise WebDriverError("本机没有 chromedriver / geckodriver")
    name, binary = found
    is_firefox = "gecko" in name

    port = 9515 if not is_firefox else 4444
    base = f"http://127.0.0.1:{port}"
    args = [binary, f"--port={port}", "--allowed-ips=127.0.0.1"]
    if is_firefox:
        args.append("--log=warn")
    process = subprocess.Popen(args, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    session_id: Optional[str] = None
    try:
        deadline = time.time() + 15
        while time.time() < deadline:
            try:
                _wd_request(base, "GET", "/status", timeout=2)
                break
            except Exception:
                if process.poll() is not None:
                    raise WebDriverError("浏览器驱动启动失败")
                time.sleep(0.2)
        else:
            raise WebDriverError("浏览器驱动未能在 15 秒内就绪")

        options_key = "moz:firefoxOptions" if is_firefox else "goog:chromeOptions"
        browser = "firefox" if is_firefox else "chrome"
        switches = ["--no-first-run", "--no-default-browser-check", "--disable-dev-shm-usage"]
        if headless:
            switches.append("--headless=new" if not is_firefox else "--headless")
        if os.geteuid() == 0 and not is_firefox:
            switches.append("--no-sandbox")
        created = _wd_request(base, "POST", "/session", {
            "capabilities": {"alwaysMatch": {
                "browserName": browser,
                options_key: {"args": switches},
            }}
        }, timeout=30)
        session_id = (created.get("value") or {}).get("sessionId") or created.get("sessionId")
        if not session_id:
            raise WebDriverError("无法创建浏览器会话")
        _wd_request(base, "POST", f"/session/{session_id}/url", {"url": LOGIN_URL}, timeout=30)
        if on_status:
            on_status("浏览器已打开，请扫码或输入账号密码登录（最长等待 5 分钟）")

        deadline = time.time() + timeout
        last_note = 0.0
        while time.time() < deadline:
            try:
                result = _wd_request(base, "GET", f"/session/{session_id}/cookie", timeout=10)
            except Exception:
                break
            raw_cookies = result.get("value") or []
            collected = {
                item["name"]: item["value"]
                for item in raw_cookies
                if item.get("name") and item.get("value") is not None
                and ("baidu" in str(item.get("domain", "")) or item["name"] in LOGIN_KEYS)
            }
            if any(key in collected for key in LOGIN_KEYS):
                save_cookies(collected)
                return collected
            if on_status and time.time() - last_note > 20:
                last_note = time.time()
                on_status("仍在等待登录…")
            time.sleep(2)
        raise WebDriverError("等待登录超时，请重试")
    finally:
        if session_id:
            try:
                _wd_request(base, "DELETE", f"/session/{session_id}", timeout=5)
            except Exception:
                pass
        process.terminate()
        try:
            process.wait(timeout=5)
        except subprocess.TimeoutExpired:
            process.kill()


def login_auto(timeout: int = 300, headless: bool = False,
               on_status: Optional[Callable[[str], None]] = None) -> Dict[str, str]:
    """自动登录：优先浏览器驱动，失败时尝试 Firefox cookie 数据库。"""
    message = []
    if _find_driver():
        try:
            cookies = login_via_browser(timeout=timeout, headless=headless, on_status=on_status)
            _set_login_state("success", "登录成功，凭证已保存", "浏览器自动登录")
            return cookies
        except Exception as exc:
            message.append(str(exc))
    try:
        cookies = from_firefox()
        if has_login(cookies):
            save_cookies(cookies)
            _set_login_state("success", "已从 Firefox 导入登录态", "Firefox Cookie")
            return cookies
    except Exception as exc:
        message.append(f"读取 Firefox Cookie 失败：{exc}")
    _set_login_state("error", "；".join(message) or "没有找到可用的自动登录方式")
    raise WebDriverError("；".join(message) or "没有找到可用的自动登录方式")


def login_auto_async(timeout: int = 300, headless: bool = False) -> None:
    """给网页面板调用的异步入口；状态写进 LOGIN_STATE。"""
    with _LOGIN_LOCK:
        if LOGIN_STATE.get("state") in ("starting", "waiting"):
            return
        LOGIN_STATE.update(state="starting", message="正在启动浏览器…", method="", updated=time.time())

    def worker():
        try:
            login_auto(timeout=timeout, headless=headless,
                       on_status=lambda text: _set_login_state("waiting", text, "浏览器自动登录"))
        except Exception as exc:
            _set_login_state("error", str(exc))

    threading.Thread(target=worker, name="yunx-login", daemon=True).start()
